'use strict'

const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const root = path.resolve(__dirname, '..')
const source = 'docs/冶金砷领域专家知识与回答规范.md'
const englishSource = 'docs/metallurgical-arsenic-expert-standard.en.md'
const normalize = text => text.replace(/\r\n/g, '\n')

function validateBudget(rules) {
  const core = rules.filter(rule => rule.core)
  const ruleChars = rule => rule.content.length + rule.title.length + rule.id.length + 10
  if (core.length > 10 || core.reduce((sum, rule) => sum + ruleChars(rule), 250) > 6000 ||
      rules.some(rule => ruleChars(rule) + 250 > 6000)) throw new Error('规则正文超出运行预算')
}

function compilePolicy(markdown, englishMarkdown) {
  const text = normalize(markdown)
  const block = text.match(/```expert-policy-index\n([\s\S]*?)\n```/)
  if (!block) throw new Error('规范缺少 expert-policy-index')
  const index = JSON.parse(block[1])
  if (!index.version || index.policyStatus !== 'software_active' ||
      !Array.isArray(index.domainTerms) || !index.domainTerms.length ||
      index.domainTerms.some(term => typeof term !== 'string' || !term.trim()) ||
      !Array.isArray(index.rules) || !index.rules.length) throw new Error('规则索引无效')
  const sections = new Map()
  for (const match of text.matchAll(/^### (MET-AS-R\d{3})：([^\n]+)\n([\s\S]*?)(?=^#{1,3} |$(?![\s\S]))/gm)) {
    if (sections.has(match[1])) throw new Error(`重复规则正文: ${match[1]}`)
    sections.set(match[1], { title: match[2], content: match[3].trim() })
  }
  const seen = new Set()
  const rules = index.rules.map(item => {
    const section = sections.get(item.id)
    if (!section || seen.has(item.id) || !Array.isArray(item.keywords) ||
        item.keywords.some(term => typeof term !== 'string' || !term.trim())) {
      throw new Error(`规则缺失、重复或关键词无效: ${item.id}`)
    }
    if (!section.content.includes('- 要求：') && !section.content.includes('- 必须检查：')) {
      throw new Error(`规则缺少完整要求: ${item.id}`)
    }
    seen.add(item.id)
    return { id: item.id, core: item.core === true, keywords: item.keywords, ...section }
  })
  if (sections.size !== seen.size) throw new Error('存在未纳入索引的规则正文')
  validateBudget(rules)
  const bundle = {
    version: index.version,
    policyStatus: index.policyStatus,
    technicalReviewStatus: index.technicalReviewStatus,
    source,
    sourceHash: crypto.createHash('sha256').update(text).digest('hex'),
    domainTerms: index.domainTerms,
    rules
  }
  if (englishMarkdown !== undefined) {
    const en = normalize(englishMarkdown)
    const metadataBlock = en.match(/```expert-policy-translation\n([\s\S]*?)\n```/)
    if (!metadataBlock) throw new Error('英文规范缺少版本元数据')
    const metadata = JSON.parse(metadataBlock[1])
    if (metadata.version !== index.version || metadata.language !== 'en' || metadata.indexSource !== source) {
      throw new Error('中英文规范版本或来源不一致')
    }
    const translations = new Map()
    for (const match of en.matchAll(/^### (MET-AS-R\d{3}): ([^\n]+)\n([\s\S]*?)(?=^#{1,3} |$(?![\s\S]))/gm)) {
      const content = match[3].trim()
      if (translations.has(match[1]) || !content.includes('- Requirement:') || !content.includes('- Trigger:') || !content.includes('- Output:')) {
        throw new Error(`英文规则重复或不完整: ${match[1]}`)
      }
      translations.set(match[1], { id: match[1], title: match[2], content })
    }
    if (translations.size !== rules.length || rules.some(rule => !translations.has(rule.id))) {
      throw new Error('中英文规则 ID 不一致')
    }
    const translatedRules = rules.map(rule => ({ ...translations.get(rule.id), core: rule.core }))
    validateBudget(translatedRules)
    bundle.translations = { en: {
      source: englishSource,
      sourceHash: crypto.createHash('sha256').update(en).digest('hex'),
      rules: translatedRules
    } }
  }
  return bundle
}

function build(check = false) {
  const bundle = JSON.stringify(compilePolicy(
    fs.readFileSync(path.join(root, source), 'utf8'),
    fs.readFileSync(path.join(root, englishSource), 'utf8')
  ), null, 2) + '\n'
  const enginePath = 'cloudfunctions/processKnowledge/lib/expertPolicy.js'
  const engine = normalize(fs.readFileSync(path.join(root, enginePath), 'utf8'))
  const outputs = [
    ['web-admin/server/utils/focusedEvidence.js', normalize(fs.readFileSync(path.join(root,'cloudfunctions/processKnowledge/lib/focusedEvidence.js'),'utf8'))],
    ['web-admin/shared/miniappAnswerPrompt.json', JSON.stringify(require(path.join(root, 'config/answerPrompt.js')), null, 2) + '\n'],
    ['cloudfunctions/processKnowledge/lib/expertRules.json', bundle],
    ['web-admin/server/utils/expertRules.json', bundle],
    ['web-admin/server/utils/expertPolicy.js', '// Generated by tools/build-expert-policy.js; edit ' + enginePath + ' instead.\n' + engine]
  ]
  for (const [relative, content] of outputs) {
    const target = path.join(root, relative)
    if (check) {
      if (!fs.existsSync(target) || normalize(fs.readFileSync(target, 'utf8')) !== content) {
        throw new Error(`专家规范产物过期: ${relative}；请执行 npm run expert:build`)
      }
    } else {
      fs.writeFileSync(target, content, 'utf8')
    }
  }
  console.log(check ? '专家规范与两个部署包一致。' : '已生成云函数与流式服务专家规则包。')
}

if (require.main === module) build(process.argv.includes('--check'))
module.exports = { compilePolicy, build }
